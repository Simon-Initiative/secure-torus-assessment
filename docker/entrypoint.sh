#!/bin/sh
set -eu

if [ "${1:-}" = bootstrap ]; then
    owner="$(stat -c '%u:%g' /workspace/secure-assessment-plugin)"
    if [ -d /workspace/moodle ] && [ ! -e /workspace/moodle/.git ] &&
            [ -z "$(ls -A /workspace/moodle)" ]; then
        chown "$owner" /workspace/moodle
    fi
    exec gosu "$owner" sh /workspace/secure-assessment-plugin/docker/bootstrap.sh
fi

if [ "${1:-}" = init ]; then
    sh docker/generate-certs.sh
fi
# Each container has its own trust store, including the cron container.
if [ "$(id -u)" = 0 ]; then
    cp /etc/moodle/tls/root-ca.crt /usr/local/share/ca-certificates/moodle-torus-local.crt
    update-ca-certificates >/dev/null
fi

case "${1:-}" in
    init)
        # Never overwrite an existing configuration for another environment.
        if [ -e config.php ]; then
            if ! grep -q 'MOODLE_LOCAL_DOCKER_CONFIG' config.php; then
                echo 'Existing config.php is not Docker-managed. Move it aside before starting Compose.' >&2
                exit 1
            fi
        else
            cat > config.php <<'PHP'
<?php
// MOODLE_LOCAL_DOCKER_CONFIG: generated by docker/entrypoint.sh.
require_once(__DIR__ . '/docker/config.php');
PHP
        fi
        mkdir -p /var/www/moodledata vendor
        chown www-data:www-data /var/www/moodledata vendor
        # Install the locked runtime dependencies inside Docker's vendor volume.
        checksum="$(sha256sum composer.json composer.lock | sha256sum | cut -d ' ' -f 1)"
        if [ ! -f vendor/autoload.php ] || [ "$(cat vendor/.moodle-composer-hash 2>/dev/null || true)" != "$checksum" ]; then
            gosu www-data env COMPOSER_HOME=/tmp/composer composer install --no-dev --prefer-dist --no-interaction --no-progress
            printf '%s\n' "$checksum" > vendor/.moodle-composer-hash
        fi
        exec gosu www-data php docker/install.php
        ;;
    cron)
        exec gosu www-data "$0" cron-worker
        ;;
    cron-worker)
        trap 'exit 0' TERM INT
        while true; do
            php admin/cli/cron.php --keep-alive=0 || echo 'Moodle cron failed; retrying in 60 seconds.' >&2
            sleep 60 &
            wait $!
        done
        ;;
    *)
        exec docker-php-entrypoint "$@"
        ;;
esac
